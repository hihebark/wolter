import { ColumnType, TableDef, WOLTER_TABLES, indexName, tableName, validatePrefix } from './schema';

const PRISMA_TYPE: Record<ColumnType, string> = { text: 'String', int: 'Int', bigint: 'BigInt', real: 'Float' };

const MODEL_NAME: Record<string, string> = { metrics: 'WolterMetric', events: 'WolterEvent' };

function camelCase(name: string): string {
  return name.replace(/_([a-z])/g, (_, c: string) => c.toUpperCase());
}

function renderModel(table: TableDef, prefix: string): string {
  const lines: string[] = [];
  if (table.autoIncrementId) {
    lines.push('  id           BigInt   @id @default(autoincrement())');
  }
  for (const col of table.columns) {
    const type = PRISMA_TYPE[col.type] + (col.nullable ? '?' : '');
    lines.push(`  ${camelCase(col.name).padEnd(12)} ${type.padEnd(8)} @map("${col.name}")`);
  }
  if (table.primaryKey) {
    lines.push(`\n  @@id([${table.primaryKey.map(camelCase).join(', ')}])`);
  }
  for (const idx of table.indexes) {
    lines.push(`  @@index([${idx.columns.map(camelCase).join(', ')}], name: "${indexName(table, prefix, idx)}")`);
  }
  lines.push(`  @@map("${tableName(table, prefix)}")`);
  return `model ${MODEL_NAME[table.name]} {\n${lines.join('\n')}\n}`;
}

export function renderPrismaSchema(prefix: string): string {
  validatePrefix(prefix);
  return `// Generated by \`wolter-migrate generate --target prisma\`. Append these models
// to schema.prisma, then run \`npx prisma migrate dev --name add_wolter_tables\`.

${WOLTER_TABLES.map((t) => renderModel(t, prefix)).join('\n\n')}
`;
}
