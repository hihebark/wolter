import { SqlDialect, renderDropSchemaSql, renderSchemaSql } from './sql';

// One queryRunner.query() call per complete SQL statement. Must NOT split
// each statement further (e.g. by '\n') — a CREATE TABLE statement's column
// list spans multiple lines and is still exactly one statement.
function asQueryRunnerCalls(statements: string[]): string {
  return statements.map((statement) => `    await queryRunner.query(\`${statement.replace(/`/g, '\\`')}\`);`).join('\n');
}

export function renderTypeOrmMigration(className: string, prefix: string, dialect: SqlDialect): string {
  return `import { MigrationInterface, QueryRunner } from 'typeorm';

// Generated by \`wolter-migrate generate --target typeorm\` — creates the tables
// a WolterStorageDriver reads and writes. Safe to edit or re-generate; this is
// a normal migration, tracked by TypeORM like any other.
export class ${className} implements MigrationInterface {
  name = '${className}';

  public async up(queryRunner: QueryRunner): Promise<void> {
${asQueryRunnerCalls(renderSchemaSql(prefix, dialect))}
  }

  public async down(queryRunner: QueryRunner): Promise<void> {
${asQueryRunnerCalls(renderDropSchemaSql(prefix, dialect))}
  }
}
`;
}
